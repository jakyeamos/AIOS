import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const uiRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(uiRoot, "..");
const registryPath = path.join(repoRoot, "config", "workflows", "registry.json");
const outputPath = path.join(uiRoot, "server", "generated", "workflow-catalog.ts");
const registry = JSON.parse(fs.readFileSync(registryPath, "utf8"));

const strings = (value) => (Array.isArray(value) ? value.filter((item) => typeof item === "string") : []);
const workflows = (registry.workflows ?? [])
  .filter((workflow) => workflow && typeof workflow === "object")
  .map((workflow) => {
    const key = typeof workflow.key === "string" ? workflow.key : "unknown-workflow";
    return {
      key,
      name: typeof workflow.name === "string" ? workflow.name : key,
      summary:
        typeof workflow.purpose_long === "string"
          ? workflow.purpose_long
          : typeof workflow.purpose === "string"
            ? workflow.purpose
            : "Workflow registered without a summary.",
      triggers: strings(workflow.trigger_hints),
      deliverables: strings(workflow.output_contract),
      validation: strings(workflow.required_validations),
      defaultBackendKey: "codex-managed-runtime",
      isSeedData: false,
    };
  });

const generated = `// Generated by scripts/generate-workflow-catalog.mjs. Do not edit by hand.\n\nimport type { WorkflowTemplate } from "@/lib/control-plane";\n\nexport const workflowTemplateCatalog: WorkflowTemplate[] = ${JSON.stringify(workflows, null, 2)};\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error("Workflow catalog is stale: run pnpm workflows:generate.");
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(outputPath, generated, "utf8");
}
