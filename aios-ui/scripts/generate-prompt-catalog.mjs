import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const uiRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(uiRoot, "..");
const registryPath = path.join(repoRoot, "prompts", "registry.json");
const outputPath = path.join(uiRoot, "server", "generated", "prompt-catalog.ts");

const stringifyInput = (value) => {
  if (typeof value === "string") {
    return value;
  }

  if (value && typeof value === "object" && !Array.isArray(value)) {
    const [key, input] = Object.entries(value)[0] ?? [];
    if (key && typeof input === "string") {
      return `${key}: ${input}`;
    }
  }

  return "";
};

const stringArray = (value) => (Array.isArray(value) ? value.map(stringifyInput).filter(Boolean) : []);

const bodyHash = (markdown) => {
  const lines = markdown.split(/\r?\n/);
  const bodyStart = lines[0] === "---" ? lines.findIndex((line, index) => index > 0 && line.trim() === "---") + 1 : 0;
  const body = lines.slice(bodyStart).join("\n").replace(/^\n+/, "");
  return crypto.createHash("sha256").update(body, "utf8").digest("hex");
};

const registry = JSON.parse(fs.readFileSync(registryPath, "utf8"));
const templates = (registry.templates ?? []).flatMap((template) => {
  const id = typeof template.id === "string" ? template.id : "";
  const file = typeof template.file === "string" ? template.file : "";
  if (!id || !file) {
    return [];
  }

  const templatePath = path.join(repoRoot, file);
  if (!fs.existsSync(templatePath)) {
    throw new Error(`Prompt template file is missing: ${templatePath}`);
  }

  return [{
    id,
    name: typeof template.name === "string" ? template.name : "Unnamed template",
    version: typeof template.version === "string" ? template.version : "unknown",
    classification: typeof template.classification === "string" ? template.classification : "other",
    tags: Array.isArray(template.tags) ? template.tags.filter((tag) => typeof tag === "string") : [],
    purpose: typeof template.purpose === "string" ? template.purpose : "",
    requiredInputs: stringArray(template.required_inputs),
    optionalInputs: stringArray(template.optional_inputs),
    lastUpdated: typeof template.last_updated === "string" ? template.last_updated : "",
    file,
    hash: bodyHash(fs.readFileSync(templatePath, "utf8")),
  }];
});

const typeDefinition = `export type GeneratedPromptTemplate = {
  id: string;
  name: string;
  version: string;
  classification: string;
  tags: string[];
  purpose: string;
  requiredInputs: string[];
  optionalInputs: string[];
  lastUpdated: string;
  file: string;
  hash: string;
};

`;
const catalogDefinition = `export const promptTemplateCatalog: GeneratedPromptTemplate[] = ${JSON.stringify(templates, null, 2)};\n`;
const generated = "// Generated by scripts/generate-prompt-catalog.mjs. Do not edit by hand.\n\n" + typeDefinition + catalogDefinition;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error("Prompt catalog is stale: run pnpm prompts:generate.");
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(outputPath, generated, "utf8");
}
